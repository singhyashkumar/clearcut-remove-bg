#!/usr/bin/env node
/**
 * check-india-release.mjs — read-only release checker for the four India pages.
 *
 * Issues HTTP GET requests only and writes nothing, so it is safe to run against
 * production. Expectations are read from docs/seo/india-page-content.json (the
 * four new pages) and docs/seo/release-corrections.json (preserved invariants and
 * the strings that the corrections intentionally remove).
 *
 * Usage:
 *   node scripts/check-india-release.mjs --offline
 *   node scripts/check-india-release.mjs [origin] [--offline]
 *
 *   node scripts/check-india-release.mjs                       # https://clearcutt.in
 *   node scripts/check-india-release.mjs https://clearcutt.in
 *   node scripts/check-india-release.mjs --offline             # local files only, no network
 *
 * Exit codes: 0 = no failures (warnings allowed), 1 = at least one FAIL, 2 = cannot run.
 *
 * Deliberately not checked here (do these by hand in Search Console):
 *   - Resubmit https://clearcutt.in/sitemap.xml.
 *   - Request indexing for the 14 canonical HTML URLs only. /llms.txt is a content
 *     check, never a Request Indexing target.
 *
 * This file is independent of scripts/seo.mjs, scripts/verify-dist.mjs and
 * scripts/verify-live.mjs: it imports nothing from them and duplicates none of
 * their logic.
 */

import { readFileSync } from 'node:fs';
import { resolve, join } from 'node:path';

const ROOT = new URL('../', import.meta.url);
const CONTENT_PATH = new URL('docs/seo/india-page-content.json', ROOT);
const CORRECTIONS_PATH = new URL('docs/seo/release-corrections.json', ROOT);

const args = process.argv.slice(2);
const OFFLINE = args.includes('--offline');
const DIST = args.find(a => a.startsWith('--dist='))?.slice(7);
const DIST_ROOT = DIST ? resolve(DIST) : null;
const ORIGIN = (args.find((a) => !a.startsWith('--')) || 'https://clearcutt.in').replace(/\/+$/, '');

/** The 10 routes generated by the shared template before these four pages (base commit bef5689). */
const EXISTING_SLUGS = [
  '',
  'how-to-remove-background',
  'transparent-background',
  'remove-background-products',
  'remove-background-portraits',
  'remove-background-animals',
  'remove-background-cars',
  'about',
  'privacy',
  'contact',
];

/** Strings the R-corrections intentionally remove. Presence is a WARNING (correction not yet applied), never a requirement. */
const OBSOLETE_STRINGS = [
  { text: '(alpha > 4)', ids: 'R3' },
  { text: 'forensic RAM-erasure guarantee', ids: 'R4' },
  { text: 'forensic RAM erasure ki guarantee', ids: 'R4' },
  { text: 'isolates dark ink on plain paper', ids: 'R1' },
  { text: 'alpha opacity around them', ids: 'R1, R12' },
  { text: 'alpha mask', ids: 'R12' },
  { text: 'uncompressed-alpha raster PNG', ids: 'R12' },
  { text: 'for finer stroke retention', ids: 'R2' },
  { text: '16 category-specific image guideline PDFs', ids: 'R7' },
  { text: '16 category-specific cataloging guidelines', ids: 'R7' },
  { text: 'Meesho catalogs group 1 to 9 products', ids: 'R11' },
  { text: 'often require JPEG and fixed aspect ratios', ids: 'R6' },
];

const PROHIBITED_SCHEMA_TYPES = ['AggregateRating', 'Review'];
const TYPE_WARNING = /(^|[a-z])Rating$/;

const results = [];
const record = (level, name, detail = '') => results.push({ level, name, detail });
const check = (cond, name, detail = '') => record(cond ? 'PASS' : 'FAIL', name, detail);
const warn = (cond, name, detail = '') => record(cond ? 'PASS' : 'WARN', name, detail);
const info = (name, detail = '') => record('INFO', name, detail);

/* ------------------------------------------------------------------ helpers */

function readJson(url, label) {
  try {
    return JSON.parse(readFileSync(url, 'utf8'));
  } catch (error) {
    console.error(`Cannot read ${label} (${url.pathname}): ${error.message}`);
    process.exit(2);
  }
}

function decodeEntities(input) {
  return String(input)
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&#0?39;/g, "'")
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&');
}

const norm = (s) => decodeEntities(s).replace(/\s+/g, ' ').trim();

/** Strip scripts and tags, decode entities, collapse whitespace: the visible text of a page. */
function visibleText(html) {
  return norm(
    decodeEntities(html)
      .replace(/<script[\s\S]*?<\/script>/gi, ' ')
      .replace(/<style[\s\S]*?<\/style>/gi, ' ')
      .replace(/<!--[\s\S]*?-->/g, ' ')
      .replace(/<[^>]+>/g, ' '),
  );
}

const typeArray = (value) => (Array.isArray(value) ? value : value ? [value] : []);

function flatten(node, out = []) {
  if (Array.isArray(node)) node.forEach((n) => flatten(n, out));
  else if (node && typeof node === 'object') {
    out.push(node);
    Object.values(node).forEach((v) => flatten(v, out));
  }
  return out;
}

function jsonLdNodes(html) {
  const nodes = [];
  let parseErrors = 0;
  for (const m of html.matchAll(/<script[^>]*type="application\/ld\+json"[^>]*>([\s\S]*?)<\/script>/gi)) {
    try {
      nodes.push(...flatten(JSON.parse(m[1])));
    } catch {
      parseErrors += 1;
    }
  }
  return { nodes, parseErrors };
}

function resolveField(content, field) {
  const match = /^pages\[(\d+)\]\.(.+)$/.exec(field);
  if (!match) return { ok: false, reason: 'field does not start with pages[i]' };
  const page = content.pages?.[Number(match[1])];
  if (!page) return { ok: false, reason: `pages[${match[1]}] does not exist` };
  let node = page;
  for (const token of match[2].split('.')) {
    const indexed = /^([A-Za-z]+)\[(\d+)\]$/.exec(token);
    if (indexed) {
      node = node?.[indexed[1]]?.[Number(indexed[2])];
    } else {
      node = node?.[token];
    }
    if (node === undefined) return { ok: false, reason: `path stops at "${token}"` };
  }
  return { ok: true, value: typeof node === 'string' ? node : JSON.stringify(node) };
}

/* -------------------------------------------------------------------- input */

const content = readJson(CONTENT_PATH, 'content file');
const corrections = readJson(CORRECTIONS_PATH, 'corrections file');

let ledgerText = '';
try {
  ledgerText = readFileSync(new URL('docs/seo/india-page-sources.md', ROOT), 'utf8');
} catch {
  ledgerText = '';
}

/** The body of one `### \`SRC-ID\`` ledger entry, or '' when the heading is absent. */
function ledgerSection(id) {
  const parts = ledgerText.split(/^### /m);
  const hit = parts.find((p) => p.startsWith(`\`${id}\``));
  return hit ?? '';
}

const pages = content.pages ?? [];
const newSlugs = pages.map((p) => p.slug);
const allSlugs = [...EXISTING_SLUGS, ...newSlugs];
const routeOf = (slug) => (slug === '' ? '/' : `/${slug}/`);

console.log(`\nClearcut India release checker — ${OFFLINE ? 'OFFLINE (local files only, no network)' : DIST ? 'BUILT FILES (no network)' : ORIGIN}`);
console.log(`content:     docs/seo/india-page-content.json (schema ${content.schemaVersion ?? '?'} · verified ${content.verifiedDate ?? '?'})`);
console.log(`corrections: docs/seo/release-corrections.json (${(corrections.corrections ?? []).length} items · base ${String(corrections.contentCommit ?? '?').slice(0, 7)})`);
console.log(`routes:      ${allSlugs.length} (${EXISTING_SLUGS.length} existing + ${newSlugs.length} new)\n`);

/* ------------------------------------------------- offline structural checks */

{
  check(newSlugs.length === 4, 'content declares 4 India pages', newSlugs.join(', '));
  const badSlugs = pages.filter((p) => !p.slug || !p.title || !p.description || !p.h1 || !p.lang);
  check(badSlugs.length === 0, 'every page has slug, title, description, h1 and lang', badSlugs.map((p) => p.slug || '?').join(', '));

  const list = corrections.corrections ?? [];
  const allowedActions = new Set(['replace', 'remove', 'append', 'keep']);
  const allowedClaims = new Set(['verified-fact', 'inference', 'hypothesis', 'editorial']);

  const badShape = list.filter((c) => !c.id || !c.rank || !c.target || !c.action || !c.claimType || c.slug === undefined);
  check(badShape.length === 0, 'every correction has id, rank, slug, target, action and claimType', badShape.map((c) => c.id || '?').join(', '));
  check(list.every((c) => allowedActions.has(c.action)), 'every action is replace | remove | append | keep');
  check(list.every((c) => allowedClaims.has(c.claimType)), 'every claimType is verified-fact | inference | hypothesis | editorial');

  const unresolved = [];
  const staleCurrent = [];
  for (const c of list) {
    if (c.target === 'content') {
      const resolved = resolveField(content, c.field);
      if (!resolved.ok) unresolved.push(`${c.id}: ${c.field} (${resolved.reason})`);
      else if ((c.action === 'replace' || c.action === 'remove') && !String(resolved.value).includes(c.status === 'applied' ? (c.appliedText || c.proposedText) : c.currentText)) {
        staleCurrent.push(`${c.id}: expected text not found at ${c.field}`);
      }
    } else if (c.target === 'ledger') {
      const id = String(c.field).replace(/^ledger:/, '');
      if (id === 'DOCUMENT-LEVEL') continue;
      if (!ledgerText) {
        unresolved.push(`${c.id}: docs/seo/india-page-sources.md is unreadable`);
        continue;
      }
      const section = ledgerSection(id);
      if (!section) unresolved.push(`${c.id}: ledger has no "### \`${id}\`" entry`);
      else if (c.action === 'replace' && !section.includes(c.status === 'applied' ? (c.appliedText || c.proposedText) : c.currentText)) {
        staleCurrent.push(`${c.id}: expected text not found in ledger entry ${id}`);
      }
    }
  }
  check(unresolved.length === 0, 'every content correction field resolves in the content JSON', unresolved.join(' | '));
  check(staleCurrent.length === 0, 'every pending or applied correction matches its expected text', staleCurrent.join(' | '));

  const missingProposed = list.filter((c) => c.action !== 'keep' && !c.proposedText);
  check(missingProposed.length === 0, 'every replace/remove/append correction carries proposedText', missingProposed.map((c) => c.id).join(', '));

  const hypotheses = list.filter((c) => c.claimType === 'hypothesis' || c.claimType === 'inference');
  for (const c of hypotheses) {
    info(`${c.id} claimType=${c.claimType}`, c.claimDetail ? c.claimDetail.slice(0, 100) + '…' : 'no claimDetail recorded');
  }
  const needsTest = (corrections.releaseGate?.runtimeTestsRequiredBeforePublishingBehaviourClaims ?? []);
  check(
    needsTest.every((id) => (list.find((c) => c.id === id || c.id.startsWith(`${id}-`)) ?? {}).verification),
    'every behaviour claim that needs a runtime test records how to run it',
    needsTest.join(', '),
  );

  const preserve = corrections.preserve ?? [];
  check(preserve.length > 0, 'corrections file lists preserved invariants');
  info('obsolete strings tracked', `${OBSOLETE_STRINGS.length} strings mapped to ${[...new Set(OBSOLETE_STRINGS.map((o) => o.ids))].length} correction ids`);
}

if (OFFLINE) {
  report();
}

/* -------------------------------------------------------------- live checks */

const cache = new Map();
async function get(path) {
  const url = path.startsWith('http') ? path : `${ORIGIN}${path}`;
  if (cache.has(url)) return cache.get(url);
  if (DIST_ROOT) {
    const target = new URL(url);
    if (target.origin !== new URL(ORIGIN).origin) throw new Error('Built-file mode only reads local site routes');
    const pathname = decodeURIComponent(target.pathname);
    const file = resolve(DIST_ROOT, '.' + pathname, pathname.endsWith('/') ? 'index.html' : '');
    if (!file.startsWith(DIST_ROOT + '/')) throw new Error('Path escaped the build directory');
    let entry;
    try { entry = { url, status: 200, body: readFileSync(file, 'utf8'), location: '' }; }
    catch { entry = { url, status: 404, body: '', location: '' }; }
    cache.set(url, entry);
    return entry;
  }
  let entry;
  try {
    const response = await fetch(url, { redirect: 'manual', headers: { 'user-agent': 'clearcut-india-release-check/1.0' } });
    entry = {
      url,
      status: response.status,
      body: response.status === 200 ? await response.text() : '',
      location: response.headers.get('location') || '',
    };
  } catch (error) {
    entry = { url, status: 0, body: '', location: '', error: String(error?.message || error) };
  }
  cache.set(url, entry);
  return entry;
}

for (const slug of allSlugs) {
  const route = routeOf(slug);
  const { status } = await get(route);
  check(status === 200, `GET ${route} → 200`, status ? `HTTP ${status}` : 'network error');
}

for (const page of pages) {
  const route = routeOf(page.slug);
  const { status, body } = await get(route);
  if (status !== 200) {
    check(false, `${page.slug}: page reachable for content checks`, `HTTP ${status}`);
    continue;
  }

  const text = visibleText(body);
  const htmlTitle = norm((body.match(/<title[^>]*>([\s\S]*?)<\/title>/i) || [, ''])[1]);
  const metaDescription = norm((body.match(/<meta[^>]*name="description"[^>]*content="([^"]*)"/i) || [, ''])[1]);
  const canonical = (body.match(/<link[^>]*rel="canonical"[^>]*href="([^"]*)"/i) || [, ''])[1];
  const lang = (body.match(/<html[^>]*lang="([^"]*)"/i) || [, ''])[1];
  const h1s = [...body.matchAll(/<h1[^>]*>([\s\S]*?)<\/h1>/gi)].map((m) => norm(m[1]));
  const h2s = [...body.matchAll(/<h2[^>]*>([\s\S]*?)<\/h2>/gi)].map((m) => norm(m[1]));

  check(htmlTitle === page.renderedTitle, `${page.slug}: <title> equals renderedTitle`, htmlTitle);
  warn(htmlTitle.length < 60, `${page.slug}: <title> under 60 characters (editorial guidance, not a ranking guarantee)`, `${htmlTitle.length}`);
  check(metaDescription === page.description, `${page.slug}: meta description equals JSON`, `${metaDescription.length} chars`);
  warn(metaDescription.length < 155, `${page.slug}: meta description under 155 characters (editorial guidance)`, `${metaDescription.length}`);
  check(canonical === page.canonicalUrl, `${page.slug}: canonical is ${page.canonicalUrl}`, canonical);
  check(h1s.length === 1, `${page.slug}: exactly one <h1>`, `${h1s.length} found`);
  check(h1s[0] === page.h1, `${page.slug}: <h1> equals JSON h1 (needs the shared template to render h1, not title)`, h1s[0] ?? '');
  check(lang === page.lang, `${page.slug}: <html lang="${page.lang}"> (needs the shared template to stop hardcoding lang="en")`, `found "${lang}"`);

  const missingHeadings = page.sections.map((s) => s.heading).filter((h) => !h2s.includes(norm(h)));
  check(missingHeadings.length === 0, `${page.slug}: all ${page.sections.length} section <h2>s rendered`, missingHeadings.join(' | '));

  for (const section of page.sections.filter((s) => s.callout)) {
    const present = text.includes(norm(section.callout.text));
    if (section.callout.level === 'warning') {
      check(present, `${page.slug}: ${section.callout.level} callout rendered (${section.id})`, present ? '' : section.callout.text.slice(0, 70) + '…');
    } else {
      warn(present, `${page.slug}: ${section.callout.level} callout rendered (${section.id})`);
    }
  }

  const missingBullets = page.sections.flatMap((s) => s.bullets ?? []).filter((b) => !text.includes(norm(b).slice(0, 60)));
  warn(missingBullets.length === 0, `${page.slug}: all ${page.sections.flatMap((s) => s.bullets ?? []).length} bullets rendered`, `${missingBullets.length} missing`);

  /* FAQ parity — visible copy and schema must match the JSON exactly, entities decoded. */
  const missingQuestions = page.faqs.filter((f) => !text.includes(norm(f.question)));
  const missingAnswers = page.faqs.filter((f) => !text.includes(norm(f.answer)));
  check(missingQuestions.length === 0, `${page.slug}: all ${page.faqs.length} FAQ questions visible`, `${missingQuestions.length} missing`);
  check(missingAnswers.length === 0, `${page.slug}: all ${page.faqs.length} FAQ answers visible`, `${missingAnswers.length} missing`);

  const { nodes, parseErrors } = jsonLdNodes(body);
  check(parseErrors === 0, `${page.slug}: every JSON-LD block parses`, `${parseErrors} unparseable`);
  const faqNodes = nodes.filter((n) => typeArray(n['@type']).includes('FAQPage'));
  check(faqNodes.length >= 1, `${page.slug}: FAQPage JSON-LD present (@graph and multiple blocks supported)`, `${faqNodes.length} node(s)`);

  const entities = faqNodes.flatMap((n) => (Array.isArray(n.mainEntity) ? n.mainEntity : n.mainEntity ? [n.mainEntity] : []));
  check(entities.length === page.faqs.length, `${page.slug}: FAQPage mainEntity count is ${page.faqs.length}`, `${entities.length}`);

  const schemaPairs = new Set(entities.map((e) => `${norm(e?.name ?? '')}::${norm(e?.acceptedAnswer?.text ?? '')}`));
  const expectedPairs = page.faqs.map((f) => `${norm(f.question)}::${norm(f.answer)}`);
  const mismatched = expectedPairs.filter((pair) => !schemaPairs.has(pair));
  check(mismatched.length === 0, `${page.slug}: visible FAQs and FAQPage schema are exactly 1:1`, `${mismatched.length} mismatched`);

  /* Prohibited rating schema, by @type only. */
  const ratingNodes = nodes.filter(
    (n) => typeArray(n['@type']).some((t) => PROHIBITED_SCHEMA_TYPES.includes(t) || TYPE_WARNING.test(String(t))),
  );
  check(ratingNodes.length === 0, `${page.slug}: no AggregateRating / Review schema by type`, ratingNodes.map((n) => typeArray(n['@type']).join('/')).join(', '));
  const aggregateKey = nodes.some((n) => 'aggregateRating' in n) || /"aggregateRating"\s*:/i.test(body);
  warn(!aggregateKey, `${page.slug}: no aggregateRating property anywhere in the markup`);

  /* Corrections the integration is expected to have applied: warn only, never required. */
  const stillPresent = OBSOLETE_STRINGS.filter((o) => text.includes(norm(o.text)) || body.includes(o.text));
  warn(stillPresent.length === 0, `${page.slug}: no text that corrections R1-R12 remove`, stillPresent.map((o) => `${o.ids}:"${o.text}"`).join(' | '));

  /* Preserved invariants from the corrections file. */
  for (const rule of corrections.preserve ?? []) {
    if (rule.slug !== '*' && rule.slug !== page.slug) continue;
    for (const pattern of rule.mustContainAll ?? []) {
      check(new RegExp(pattern, 'i').test(text), `${page.slug}: ${rule.id} keeps ${pattern}`);
    }
    if (rule.mustContainAny?.length) {
      check(rule.mustContainAny.some((p) => new RegExp(p, 'i').test(text)), `${page.slug}: ${rule.id} keeps one of ${rule.mustContainAny.join(' | ')}`);
    }
    for (const pattern of rule.mustContain ?? []) {
      check(new RegExp(pattern, 'i').test(text), `${page.slug}: ${rule.id} keeps ${pattern}`);
    }
    for (const pattern of rule.mustNotContain ?? []) {
      check(!new RegExp(pattern, 'i').test(text), `${page.slug}: ${rule.id} avoids ${pattern}`);
    }
    if (rule.mustPrecede && rule.slug === page.slug) {
      const before = text.indexOf(norm(rule.mustPrecede.before));
      const after = text.indexOf(norm(rule.mustPrecede.after));
      check(before > -1 && after > -1 && before < after, `${page.slug}: ${rule.id} warning renders before the workflow`, `warning@${before} workflow@${after}`);
    }
  }

  for (const link of page.contextualLinks ?? []) {
    const target = link.href.startsWith('/#') ? link.href.split('#')[0] || '/' : link.href;
    const res = await get(target);
    check(res.status === 200, `${page.slug}: internal link ${link.href} → 200`, res.status ? `HTTP ${res.status}` : 'network error');
  }

  info(`${page.slug}: indexing`, 'Request indexing for this canonical URL only; never for /llms.txt');
}

/* ----------------------------------------------------------- site-wide checks */

const sitemap = await get('/sitemap.xml');
const locs = [...sitemap.body.matchAll(/<loc>([^<]*)<\/loc>/gi)].map((m) => m[1].trim());
const expectedLocs = new Set(allSlugs.map((slug) => `${ORIGIN}${routeOf(slug)}`));
check(sitemap.status === 200 && locs.length === expectedLocs.size, `sitemap.xml lists ${expectedLocs.size} URLs`, `${locs.length}`);
const missing = [...expectedLocs].filter((l) => !locs.includes(l));
check(missing.length === 0, 'sitemap contains every expected route', missing.join(' | '));
for (const loc of locs) {
  const res = await get(loc);
  check(res.status === 200, `sitemap URL ${loc.replace(ORIGIN, '') || '/'} → 200`, res.status ? `HTTP ${res.status}` : 'network error');
}

const robots = await get('/robots.txt');
check(robots.status === 200, 'robots.txt → 200', robots.status ? `HTTP ${robots.status}` : 'network error');
const sitemapDirective = new RegExp(`Sitemap:\\s*${ORIGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}/sitemap\\.xml`, 'i');
check(sitemapDirective.test(robots.body), `robots.txt declares ${ORIGIN}/sitemap.xml`);

const llms = await get('/llms.txt');
check(llms.status === 200, 'llms.txt → 200 (content check only — never request indexing)', llms.status ? `HTTP ${llms.status}` : 'network error');
for (const page of pages) {
  check(llms.body.includes(`/${page.slug}/`), `llms.txt lists /${page.slug}/`);
}

const home = await get('/');
for (const page of pages) {
  check(home.body.includes(`/${page.slug}/`), `homepage links to /${page.slug}/`);
}

report();

/* ---------------------------------------------------------------- reporting */

function report() {
  const failures = results.filter((r) => r.level === 'FAIL');
  const warnings = results.filter((r) => r.level === 'WARN');
  const notes = results.filter((r) => r.level === 'INFO');
  const pad = Math.max(24, ...results.map((r) => r.name.length));

  for (const r of results) {
    const mark = { PASS: ' ok ', FAIL: 'FAIL', WARN: 'warn', INFO: ' -- ' }[r.level];
    console.log(`${mark} ${r.name.padEnd(pad)}${r.detail ? `  ${r.detail}` : ''}`);
  }

  console.log(`\n${results.filter((r) => r.level === 'PASS').length} passed · ${failures.length} failed · ${warnings.length} warnings · ${notes.length} notes`);
  if (warnings.length) {
    console.log('\nWarnings (do not block release; length checks are editorial guidance, others are shared-template items or corrections not yet applied):');
    warnings.forEach((w) => console.log(` - ${w.name}${w.detail ? ` (${w.detail})` : ''}`));
  }
  if (failures.length) {
    console.log('\nFailures:');
    failures.forEach((f) => console.log(` - ${f.name}${f.detail ? ` (${f.detail})` : ''}`));
  }
  process.exit(failures.length ? 1 : 0);
}
